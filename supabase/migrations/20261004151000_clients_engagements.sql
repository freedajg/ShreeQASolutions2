-- Phase 1, step 7: clients, engagements and engagement_financials (PRD §6.1, §6.2, §6.5).
-- One client (the company, stored once) has many engagements (one per certification or
-- service), as in the Excel: "one row per client engagement/certification".
--
-- Every one of the 30 Excel columns has exactly one home:
--   clients                A-K (client details), AC (priority)
--   engagements            L-X (certification and dates), AA (relationship owner),
--                          AB (lead source), AD (remarks)
--   engagement_financials  Y (contract value), Z (payment status)
-- Contract value and payment status are in their own table so row-level security can give
-- a per-person switch (DECISIONS 03-Oct-2026, Phase 1 choice 3).
--
-- Import rule (CLAUDE.md rule 7): a missing or bad value is left empty and flagged, never
-- guessed. So apart from the client name and the client link, every Excel column is
-- nullable, and dropdown columns point at the step 6 lookups by code, so a misspelt value
-- can't be saved.
--
-- Access: row-level security is on, but there are no policies and no grants for anon or
-- authenticated yet, so nobody can read or change these tables through the API until
-- step 8 adds the rules for each role. Nothing is ever hard-deleted: rows are archived.

-- ---------------------------------------------------------------------------
-- updated_at helper (for these tables and later ones)
-- ---------------------------------------------------------------------------
create function app.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function app.touch_updated_at() from public;

-- ---------------------------------------------------------------------------
-- clients: Excel A-K, AC, plus do-not-contact (PRD §6.5)
-- ---------------------------------------------------------------------------
create table public.clients (
  id uuid primary key default gen_random_uuid(),
  -- A. Her Client ID (style SQAS-C001), kept as it is on import. Empty if missing (flagged).
  -- New IDs will be generated by the add-client form later.
  client_code text unique
    check (client_code is null or (client_code <> '' and client_code = btrim(client_code)
      and char_length(client_code) <= 50)),
  name text not null check (btrim(name) <> '' and char_length(name) <= 200), -- B, required
  industry text check (char_length(industry) <= 200), -- C
  address text check (char_length(address) <= 1000), -- D
  city text check (char_length(city) <= 200), -- E
  state_country text check (char_length(state_country) <= 200), -- F
  contact_person text check (char_length(contact_person) <= 200), -- G
  designation text check (char_length(designation) <= 200), -- H
  -- I. Needed to send follow-ups; empty = flagged, never a made-up address.
  email text check (email is null or (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' and char_length(email) <= 320)),
  phone text check (char_length(phone) <= 50), -- J
  website text check (char_length(website) <= 500), -- K
  -- AC. If a client's Excel rows disagree, the seed takes the first value and flags it.
  priority text references public.priorities (code),
  do_not_contact boolean not null default false,
  -- Who added it (null for server work: migrations, seed, import by the service role).
  created_by uuid references public.profiles (id) default auth.uid(),
  archived_at timestamptz, -- null = live; archive instead of delete
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- engagements: Excel L-X, AA, AB, AD, plus the follow-up and renewal fields (PRD §6.5)
-- ---------------------------------------------------------------------------
create table public.engagements (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id) on delete restrict,
  certification_type text references public.certification_types (code), -- L
  standard_framework text check (char_length(standard_framework) <= 200), -- M
  scope text check (char_length(scope) <= 2000), -- N
  status text references public.statuses (code), -- O
  initial_engagement_date date, -- P
  completion_date date, -- Q
  certificate_number text check (char_length(certificate_number) <= 200), -- R
  valid_from date, -- S
  valid_to date, -- T
  certification_body text check (char_length(certification_body) <= 200), -- U
  surveillance_due_date date, -- V
  last_audit_date date, -- W
  next_audit_date date, -- X
  -- AA. Relationship owner: the team member follow-ups are sent from. Step 8 lets a
  -- Consultant edit only engagements they own. Empty if the Excel name matches nobody (flagged).
  owner_id uuid references public.profiles (id),
  -- AB. On the engagement, not the client (PRD §6.2 puts it on the client): one client's
  -- rows can have different sources, and leads are counted by source (PRD FR-6).
  lead_source text references public.lead_sources (code),
  remarks text check (char_length(remarks) <= 5000), -- AD
  last_contacted_on date,
  next_follow_up_on date,
  -- The renewal date shown for this engagement is an estimate (PRD FR-4 rule 4).
  date_is_estimated boolean not null default false,
  -- Who added it. Step 8 lets Marketing edit only the leads it created.
  created_by uuid references public.profiles (id) default auth.uid(),
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- engagement_financials: Excel Y, Z. At most one row per engagement.
-- ---------------------------------------------------------------------------
create table public.engagement_financials (
  engagement_id uuid primary key references public.engagements (id) on delete restrict,
  contract_value numeric(12, 2) check (contract_value >= 0), -- Y, rupees
  payment_status text references public.payment_statuses (code), -- Z
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Indexes for the foreign keys that later rules and screens filter on.
create index clients_created_by_idx on public.clients (created_by);
create index engagements_client_id_idx on public.engagements (client_id);
create index engagements_owner_id_idx on public.engagements (owner_id);
create index engagements_status_idx on public.engagements (status);
create index engagements_created_by_idx on public.engagements (created_by);

create trigger touch_updated_at before update on public.clients
  for each row execute function app.touch_updated_at();
create trigger touch_updated_at before update on public.engagements
  for each row execute function app.touch_updated_at();
create trigger touch_updated_at before update on public.engagement_financials
  for each row execute function app.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Access: locked until step 8. RLS on with no policies, and no grants for anon or
-- authenticated (auto_expose_new_tables = false; the revoke makes it explicit).
-- ---------------------------------------------------------------------------
alter table public.clients enable row level security;
alter table public.engagements enable row level security;
alter table public.engagement_financials enable row level security;

revoke all on table public.clients, public.engagements, public.engagement_financials
  from anon, authenticated;
grant all on table public.clients, public.engagements, public.engagement_financials
  to service_role;
